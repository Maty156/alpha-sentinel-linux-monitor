"""Data models for Alpha Sentinel - normalized Event + Alert dataclasses."""

from dataclasses import dataclass, field
from typing import Optional, List, Dict, Any


@dataclass
class Event:
    """Normalized event - same field names as PS normalizer."""
    eventId: str
    hostname: str
    accountName: str
    sourceIp: str
    timestamp: str
    channel: str
    logonType: Optional[str] = None
    statusCode: Optional[str] = None
    targetUserName: Optional[str] = None
    subjectUserName: Optional[str] = None
    targetUserSid: Optional[str] = None
    workstationName: Optional[str] = None
    serviceName: Optional[str] = None
    encryptionType: Optional[str] = None
    status: Optional[str] = None
    preAuthType: Optional[str] = None
    ticketOptions: Optional[str] = None
    objectType: Optional[str] = None
    objectName: Optional[str] = None
    properties: Optional[str] = None
    accessMask: Optional[str] = None
    attributeLDAPDisplayName: Optional[str] = None
    attributeValue: Optional[str] = None
    operationType: Optional[str] = None
    operationCount: Optional[str] = None
    scriptBlockText: Optional[str] = None
    processId: Optional[str] = None
    parentProcessName: Optional[str] = None
    parentProcessId: Optional[str] = None
    newProcessName: Optional[str] = None
    commandLine: Optional[str] = None
    tokenElevationType: Optional[str] = None
    logonId: Optional[str] = None
    user: Optional[str] = None
    ruleKey: Optional[str] = None
    authenticationPackageName: Optional[str] = None
    keyLength: Optional[str] = None
    # Group membership / account management fields
    memberName: Optional[str] = None
    memberSid: Optional[str] = None
    targetDomainName: Optional[str] = None
    subjectDomainName: Optional[str] = None
    # DSRM / account control
    oldUserAccountControl: Optional[str] = None
    newUserAccountControl: Optional[str] = None
    # Process creation
    imagePath: Optional[str] = None
    serviceFileName: Optional[str] = None
    # Firewall
    settingType: Optional[str] = None
    settingValue: Optional[str] = None
    profileChanged: Optional[str] = None
    ruleName: Optional[str] = None
    # Defender
    eventSource: Optional[str] = None
    # System time
    newTime: Optional[str] = None
    # Fields read by the 4648/4657/4672/4697/4698/4728/5136 rules
    objectClass: Optional[str] = None
    privilegeList: Optional[str] = None
    processName: Optional[str] = None
    targetServerName: Optional[str] = None
    taskName: Optional[str] = None
    registryKey: Optional[str] = None
    registryValueName: Optional[str] = None
    targetGroup: Optional[str] = None
    subcategory: Optional[str] = None
    # For Linux
    osFamily: str = "windows"  # 'windows' or 'linux' - routes the event to the right rule set
    command: Optional[str] = None
    exe: Optional[str] = None
    auditd_type: Optional[str] = None
    # Additional fields
    extra: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Alert:
    """Alert generated by the engine."""
    Id: int
    Time: str
    RuleKey: str
    Rule: str
    Severity: str
    Title: str
    Mitre: str
    Remediation: str
    Description: str
    Host: str
    Account: str
    SourceIp: str
    EventId: str
    Acknowledged: bool = False
    Status: str = "New"
    Notes: str = ""
    SelfTest: bool = False
    FirstSeen: str = ""
    LastSeen: str = ""
    Count: int = 1
    Events: List[Dict[str, Any]] = field(default_factory=list)
    Entity: str = ""
    MitreId: str = ""
    MitreName: str = ""
    Tactic: str = ""
    DedupeKey: str = ""
    Fields: Optional[Dict[str, Any]] = None